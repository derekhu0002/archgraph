#!/usr/bin/env node
'use strict';

// Single-source generator for the DSH bundle's wakeup plugin.
//
// The ONLY authored source of the STEP 0 wakeup gate text is the
// <WakeupGuideline> block of argo/rules/archgraph.instructions.md (the same
// rule every host consumes). This script renders it into the shipped bundle
// artifact dsh-argo-wakeup/index.js. install-argo.ps1 copies that artifact into
// ~/.dsh/plugins, so the deployed plugin and the package copy are byte-identical
// and the gate text cannot fork.
//
// The workspace bridge needs no generation: dsh-argo-workspace/index.js is the
// single authored source and is copied verbatim by install-argo.ps1 too.
//
// Usage:
//   node scripts/gen-dsh-plugins.js          # regenerate in place
//   node scripts/gen-dsh-plugins.js --check  # exit 1 if the committed artifact is stale

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const RULE_PATH = path.join(ROOT, 'argo', 'rules', 'archgraph.instructions.md');
const WAKEUP_PATH = path.join(ROOT, 'dsh-argo-wakeup', 'index.js');

function extractWakeupGate(ruleText) {
  const text = ruleText.replace(/^\uFEFF/, '');
  const match = text.match(/<WakeupGuideline>([\s\S]*?)<\/WakeupGuideline>/);
  if (!match) {
    throw new Error(`<WakeupGuideline> block not found in ${path.relative(ROOT, RULE_PATH)}`);
  }
  return match[1].replace(/\r\n/g, '\n').trim();
}

function renderWakeupPlugin(gate) {
  return [
    '// dsh-argo-wakeup - generated by scripts/gen-dsh-plugins.js from',
    '// argo/rules/archgraph.instructions.md (single source of truth: the rule file;',
    '// this file is a deployment artifact, do not edit by hand).',
    '// DeepSeek Harness equivalent of the OpenCode hook argo/plugins/argo-wakeup.js:',
    '// registers the unconditional wakeup gate as the first system-prompt section',
    '// after the harness identity, so every session identifies its Business Actor',
    '// through the argo MCP server before responding.',
    "export const name = 'dsh-argo-wakeup'",
    "export const inject = ['systemPrompt']",
    `const WAKEUP_GATE = ${JSON.stringify(gate)}`,
    'export function apply(ctx) {',
    '  ctx.effect(() => ctx.systemPrompt.section({',
    "    name: 'argo:wakeup',",
    '    order: -90,',
    '    text: WAKEUP_GATE,',
    "  }), 'argo:wakeup.section()')",
    '}',
    '',
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const rendered = renderWakeupPlugin(extractWakeupGate(fs.readFileSync(RULE_PATH, 'utf8')));
  const raw = fs.existsSync(WAKEUP_PATH) ? fs.readFileSync(WAKEUP_PATH, 'utf8') : '';
  // Compare with normalized EOL so core.autocrlf checkouts (CRLF) are not
  // mistaken for stale content.
  const current = raw.replace(/\r\n/g, '\n');
  const rel = path.relative(ROOT, WAKEUP_PATH);

  if (check) {
    if (current !== rendered) {
      console.error(`${rel} is stale; run: node scripts/gen-dsh-plugins.js`);
      process.exit(1);
    }
    console.log(`${rel} is up to date with the rule <WakeupGuideline>.`);
    return;
  }

  if (current === rendered) {
    console.log(`${rel} already up to date.`);
    return;
  }

  fs.writeFileSync(WAKEUP_PATH, rendered, { encoding: 'utf8' });
  console.log(`wrote ${rel} from ${path.relative(ROOT, RULE_PATH)} <WakeupGuideline>.`);
}

main();
